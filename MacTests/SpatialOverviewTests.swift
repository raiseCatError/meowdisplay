import XCTest

/// Spatial Overview packing: shapes kept, bigger Mac windows bigger (clamped), no overlaps, inside
/// the margins, every window at least a comfortable tap (else more pages), stable order. The
/// vectors (fixtures/stage-peek/spatial.json, WRITE_SPATIAL_VECTORS=1) are replayed by Android.
final class SpatialOverviewTests: XCTestCase {
    typealias L = SpatialOverviewLayout

    /// A deterministic mix of Mac window sizes.
    static func windows(_ n: Int) -> [L.Item] {
        let sizes: [(Double, Double)] = [(1440, 900), (800, 600), (1200, 1000), (500, 700), (1920, 1050), (600, 400), (1000, 650), (340, 720)]
        return (0..<n).map { i in L.Item(width: sizes[i % sizes.count].0, height: sizes[i % sizes.count].1) }
    }
    static let screens: [CGSize] = [CGSize(width: 393, height: 852), CGSize(width: 852, height: 393), CGSize(width: 1032, height: 1376), CGSize(width: 320, height: 480)]

    func testInvariantsFor2To50Windows() {
        for size in Self.screens {
            for n in [1, 2, 5, 10, 20, 50] {
                let items = Self.windows(n)
                let p = L.layout(items, in: size)
                XCTAssertEqual(p.count, n)
                let bounds = CGRect(origin: .zero, size: size).insetBy(dx: L.margin - 1e-6, dy: L.margin - 1e-6)
                for (i, a) in p.enumerated() {
                    XCTAssertTrue(bounds.contains(a.rect), "\(n) in \(size): inside the margins")
                    XCTAssertGreaterThanOrEqual(min(a.rect.width, a.rect.height), L.minimumSide - 1e-6, "\(n) in \(size): tappable")
                    let aspect = min(max(items[i].width / items[i].height, L.aspectRange.lowerBound), L.aspectRange.upperBound)
                    XCTAssertEqual(Double(a.rect.width / a.rect.height), aspect, accuracy: 1e-6, "shape kept")
                    for b in p[(i + 1)...] where b.page == a.page {
                        XCTAssertFalse(a.rect.insetBy(dx: 0.5, dy: 0.5).intersects(b.rect), "\(n) in \(size): no overlap")
                    }
                }
                XCTAssertEqual(p.map(\.page), p.map(\.page).sorted(), "pages in order")
            }
        }
    }

    func testBiggerWindowsLookBiggerWithinTheClamp() {
        let p = L.layout([L.Item(width: 1600, height: 1000), L.Item(width: 400, height: 250), L.Item(width: 40, height: 25)], in: CGSize(width: 1032, height: 1376))
        XCTAssertGreaterThan(p[0].rect.width, p[1].rect.width)
        XCTAssertEqual(Double(p[2].rect.width / p[0].rect.width), L.minimumProminence, accuracy: 1e-6, "tiny windows stay findable")
    }

    func testDenseSetsPageAndKeepOneSize() {
        let p = L.layout(Self.windows(50), in: CGSize(width: 393, height: 852))
        XCTAssertGreaterThan(p.map(\.page).max() ?? 0, 0)
        let firstOfEach = Dictionary(grouping: p.indices, by: { p[$0].page }).values.map { $0.min()! }
        let same = Self.windows(50)
        for i in firstOfEach where same[i] == same[0] { XCTAssertEqual(p[i].rect.width, p[0].rect.width, accuracy: 1e-6) }
        XCTAssertEqual(p, L.layout(Self.windows(50), in: CGSize(width: 393, height: 852)), "deterministic")
    }

    func testExtremeShapesAndEmpty() {
        XCTAssertTrue(L.layout([], in: CGSize(width: 393, height: 852)).isEmpty)
        let p = L.layout([L.Item(width: 5000, height: 20), L.Item(width: 20, height: 5000), L.Item(width: 0, height: 0)], in: CGSize(width: 393, height: 852))
        XCTAssertEqual(p.count, 3)
        XCTAssertEqual(Double(p[0].rect.width / p[0].rect.height), L.aspectRange.upperBound, accuracy: 1e-6)
        XCTAssertEqual(Double(p[1].rect.width / p[1].rect.height), L.aspectRange.lowerBound, accuracy: 1e-6)
    }

    func testSharedVectors() throws {
        var cases: [[String: Any]] = []
        for size in Self.screens {
            for n in [2, 5, 10, 20, 50] {
                let items = Self.windows(n)
                cases.append(["width": Double(size.width), "height": Double(size.height),
                              "items": items.map { [$0.width, $0.height] },
                              "placements": L.layout(items, in: size).map { [Double($0.page), Double($0.rect.minX), Double($0.rect.minY), Double($0.rect.width), Double($0.rect.height)] }])
            }
        }
        let generated: [String: Any] = ["about": "Generated by MacTests/SpatialOverviewTests.swift (WRITE_SPATIAL_VECTORS=1); replayed by the Android port.",
                                        "config": ["minimumSide": L.minimumSide, "spacing": L.spacing, "margin": L.margin, "minimumProminence": L.minimumProminence],
                                        "cases": cases]
        let url = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().appendingPathComponent("fixtures/stage-peek/spatial.json")
        let data = try JSONSerialization.data(withJSONObject: generated, options: [.prettyPrinted, .sortedKeys])
        if ProcessInfo.processInfo.environment["WRITE_SPATIAL_VECTORS"] == "1" { try data.write(to: url) }
        let saved = try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? NSDictionary
        XCTAssertEqual(saved, try JSONSerialization.jsonObject(with: data) as? NSDictionary, "fixtures/stage-peek/spatial.json is stale: run with WRITE_SPATIAL_VECTORS=1")
    }
}
