import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Caret-following Zoom While Typing: the Mac's text caret (normalized, both axes) steers the
 * keyboard-open viewport in place of the last touch, with the touch as the fallback and no panning
 * while the caret stays in the comfortable inner region. The shared vectors in
 * fixtures/viewport/caret-vectors.json are generated by the Swift calculator.
 */
class RemoteViewportCaretTest {
    private val phone = CGRect(0.0, 0.0, 390.0, 844.0)

    /** Keyboard plus the typing strip cover the bottom 400 points. */
    private val visible = CGRect(0.0, 0.0, 390.0, 444.0)
    private val wide = CGSize(1920.0, 1080.0)
    private val tall = CGSize(1000.0, 1600.0)

    private fun caret(x: Double, y: Double) = CGRect(x, y, 0.002, 0.02)

    private fun open(
        remote: CGSize,
        zoom: Boolean,
        anchor: CGPoint? = null,
        caret: CGRect?,
        previous: CGRect? = null,
        view: CGRect = phone,
        visibleRect: CGRect = visible,
    ) = RemoteViewportCalculator.keyboardOpen(view, remote, visibleRect, anchor, zoom, caret = caret, previous = previous)

    private fun caretPosition(t: RemoteViewportTransform, c: CGRect) = t.viewPoint(CGPoint(c.midX, c.midY))

    private fun steps(from: Double, through: Double, by: Double): List<Double> {
        val out = ArrayList<Double>()
        var v = from
        while (v <= through + 1e-9) { out += v; v += by }
        return out
    }

    // MARK: - The caret stays visible above the keyboard

    @Test
    fun caretSitsInTheVisibleAreaAcrossTheDisplayWithZoomOnAndOff() {
        for (remote in listOf(wide, tall)) for (zoom in listOf(true, false))
            for (x in steps(0.02, 0.98, 0.16)) for (y in steps(0.04, 0.96, 0.16)) {
                val c = caret(x, y)
                val p = caretPosition(open(remote, zoom, caret = c), c)
                val what = "$remote zoom=$zoom caret=($x,$y)"
                assertTrue(what, p.y >= visible.minY && p.y <= visible.maxY)
                assertTrue(what, p.x >= visible.minX && p.x <= visible.maxX)
            }
    }

    @Test
    fun magnifiedViewFollowsTheCaretHorizontally() {
        val left = open(wide, true, caret = caret(0.04, 0.5))
        val right = open(wide, true, caret = caret(0.95, 0.5))
        assertTrue("zoom on magnifies past the view width", left.displayedRect.width > phone.width)
        assertTrue("a caret at the right edge pans the picture further left", left.displayedRect.minX > right.displayedRect.minX)
        for (t in listOf(left, right)) {
            assertTrue(t.displayedRect.minX <= visible.minX + 0.001)
            assertTrue(t.displayedRect.maxX >= visible.maxX - 0.001)
        }
    }

    @Test
    fun zoomOffNeverMovesHorizontallyBecauseThePictureAlreadyFitsAcross() {
        val normal = RemoteViewportCalculator.normal(phone, wide)
        for (x in listOf(0.02, 0.5, 0.98)) {
            val t = open(wide, false, caret = caret(x, 0.5))
            assertEquals(normal.displayedRect.minX, t.displayedRect.minX, 0.001)
            assertEquals(normal.displayedRect.width, t.displayedRect.width, 0.001)
        }
    }

    @Test
    fun zoomOnIsNeverSmallerThanZoomOff() {
        for (y in steps(0.04, 0.96, 0.12)) {
            val c = caret(0.5, y)
            val on = open(tall, true, caret = c)
            val off = open(tall, false, caret = c)
            assertTrue("y=$y", on.displayedRect.width >= off.displayedRect.width - 0.001)
        }
    }

    // MARK: - Fallback to the touch

    @Test
    fun noCaretBehavesExactlyAsTheTouchAnchorDid() {
        val anchor = CGPoint(0.2, 0.9)
        val legacy = RemoteViewportCalculator.keyboardOpen(phone, tall, visible, anchor, zoomEnabled = true)
        assertEquals(legacy, open(tall, true, anchor, caret = null))
        // A caret that cannot steer (off the display, not finite) is the same as none.
        assertEquals(legacy, open(tall, true, anchor, caret = caret(1.4, 0.5)))
        assertEquals(legacy, open(tall, true, anchor, caret = caret(0.5, -0.3)))
        assertEquals(legacy, open(tall, true, anchor, caret = CGRect(Double.NaN, 0.5, 0.0, 0.0)))
        assertEquals(legacy, open(tall, true, anchor, caret = CGRect.NULL))
    }

    @Test
    fun theCaretWinsOverTheTouchAnchor() {
        val withBoth = open(tall, true, CGPoint(0.2, 0.1), caret = caret(0.8, 0.9))
        val caretOnly = open(tall, true, null, caret = caret(0.8, 0.9))
        assertEquals(caretOnly, withBoth)
        assertNotEquals(open(tall, true, CGPoint(0.2, 0.1), caret = null), withBoth)
    }

    // MARK: - No jitter inside the comfort region

    @Test
    fun aSmallCaretMoveInsideTheInnerRegionDoesNotMoveThePicture() {
        val first = open(tall, true, caret = caret(0.40, 0.50))
        var previous = first.displayedRect
        for (step in 1..6) {
            val t = open(tall, true, caret = caret(0.40 + 0.004 * step, 0.50), previous = previous)
            assertEquals("step $step must not pan", first.displayedRect, t.displayedRect)
            previous = t.displayedRect
        }
    }

    @Test
    fun leavingTheInnerRegionRecentersOnTheCaret() {
        val first = open(tall, true, caret = caret(0.40, 0.50))
        val far = caret(0.9, 0.9)
        val moved = open(tall, true, caret = far, previous = first.displayedRect)
        assertNotEquals(first.displayedRect, moved.displayedRect)
        // The same caret with no history lands in the same place: re-centering is deterministic.
        assertEquals(open(tall, true, caret = far), moved)
        // Re-applying it with that history is a no-op: it stays put.
        assertEquals(moved, open(tall, true, caret = far, previous = moved.displayedRect))
    }

    @Test
    fun previousFromAnotherScaleIsIgnored() {
        val c = caret(0.41, 0.51)
        assertEquals(open(tall, true, caret = c), open(tall, true, caret = c, previous = CGRect(0.0, 0.0, 100.0, 100.0)))
    }

    @Test
    fun previousIsIgnoredWithoutACaret() {
        val anchor = CGPoint(0.3, 0.7)
        assertEquals(
            open(tall, true, anchor, caret = null),
            open(tall, true, anchor, caret = null, previous = CGRect(-50.0, -80.0, 585.0, 936.0)),
        )
    }

    @Test
    fun aKeyboardTooShortToUseStillFitsTheWholeDisplay() {
        val short = CGRect(0.0, 0.0, 390.0, 40.0)
        val t = open(wide, true, caret = caret(0.5, 0.5), visibleRect = short)
        assertTrue(t.displayedRect.maxY <= short.maxY + 0.001)
        assertTrue(t.isValid)
    }

    // MARK: - Shared vectors

    private fun JsonElement.num() = jsonPrimitive.double
    private fun rect(e: JsonElement?): CGRect? =
        (e as? JsonArray)?.let { CGRect(it[0].num(), it[1].num(), it[2].num(), it[3].num()) }

    @Test
    fun sharedVectorsMatch() {
        val dir = System.getProperty("meow.viewportFixtures") ?: error("meow.viewportFixtures not set")
        val root = Json.parseToJsonElement(File(dir, "caret-vectors.json").readText()).jsonObject
        val cases = root.getValue("cases").jsonArray.map { it.jsonObject }
        assertTrue(cases.size >= 10)
        for (c in cases) {
            val name = c.getValue("name").jsonPrimitive.content
            val remote = c.getValue("remote").jsonArray
            val anchor = (c["anchor"] as? JsonArray)?.let { CGPoint(it[0].num(), it[1].num()) }
            val t = RemoteViewportCalculator.keyboardOpen(
                rect(c["view"])!!, CGSize(remote[0].num(), remote[1].num()), rect(c["visible"])!!, anchor,
                c.getValue("zoom").jsonPrimitive.boolean,
                caret = rect(c["caret"]), previous = rect(c["previous"]),
            )
            val expected = rect(c["displayed"])!!
            assertEquals(name, expected.minX, t.displayedRect.minX, 1e-5)
            assertEquals(name, expected.minY, t.displayedRect.minY, 1e-5)
            assertEquals(name, expected.width, t.displayedRect.width, 1e-5)
            assertEquals(name, expected.height, t.displayedRect.height, 1e-5)
        }
    }
}
