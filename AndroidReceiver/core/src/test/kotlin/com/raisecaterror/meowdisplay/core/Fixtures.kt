        val dir = requireNotNull(System.getProperty("meow.fixtures")) { "meow.fixtures not set" }
        Json.parseToJsonElement(File(dir, "swift-vectors.json").readText()).jsonObject
    }

    val pairingCases: List<JsonObject> get() = vectors.getValue("pairing").jsonArray.map { it.jsonObject }

    fun JsonObject.str(key: String): String = getValue(key).jsonPrimitive.content
    fun JsonObject.b64(key: String): ByteArray = requireNotNull(str(key).base64Bytes()) { key }
    fun JsonObject.obj(key: String): JsonObject = getValue(key).jsonObject

    /** A party's handshake rebuilt from its recorded keys and nonce. */
    fun handshake(party: JsonObject, role: PairingRole) = PairingHandshake(
