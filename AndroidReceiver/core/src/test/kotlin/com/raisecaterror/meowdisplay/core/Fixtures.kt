        deviceID = party.str("deviceID"),
        displayName = party.str("displayName"),
        identitySPKI = party.b64("identitySPKI"),
        ephemeralKey = P256.ephemeral(party.str("ephemeralPrivateKey").hexBytes(), party.b64("ephemeralPublicKey")),
        nonce = party.b64("nonce"),
    )
}
