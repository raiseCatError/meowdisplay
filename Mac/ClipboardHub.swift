import AppKit
import Combine
import SwiftUI
import UniformTypeIdentifiers

// Unified Clipboard on the Mac (PROTOCOL.md 6.15). Off until the owner turns it on; each
// paired device (by its authenticated install id, never its name or address) then needs the
// owner's Allow (this session or always) or its stored policy. The Mac watches its own
// pasteboard's change count, reads it only when a device that may receive it is connected,
// sends the copy to those devices, applies their copies to the pasteboard (this Mac only:
// never re-broadcast through Universal Clipboard), and relays one device's copy to the
// others. Nothing is logged except kinds and sizes; nothing is kept after it is replaced.

enum ClipboardAccess: String, Codable, CaseIterable, Sendable {
    case ask, always, block
}

struct ClipboardDevicePolicy: Codable, Equatable, Sendable {
    var access: ClipboardAccess = .ask
    var direction: ClipDirection = .both

    static let `default` = ClipboardDevicePolicy()

    /// Would going from `old` to `self` give the device anything it didn't have?
    func widens(_ old: ClipboardDevicePolicy) -> Bool {
        guard access == .always else { return false }
        if old.access != .always { return true }
        return (direction.toDeviceAllowed && !old.direction.toDeviceAllowed) || (direction.toMacAllowed && !old.direction.toMacAllowed)
    }
}

/// Per-device policies in UserDefaults, keyed by peer install id. Like Files: never widened
/// while a device controls this Mac.
enum ClipboardDevicePolicyStore {
    private static let key = "clipboardDevicePolicy.v1"
    private static func load(_ d: UserDefaults) -> [String: Data] { d.dictionary(forKey: key) as? [String: Data] ?? [:] }

    static func policy(peerID: String, defaults: UserDefaults = .standard) -> ClipboardDevicePolicy {
        load(defaults)[peerID].flatMap { try? JSONDecoder().decode(ClipboardDevicePolicy.self, from: $0) } ?? .default
    }

    @discardableResult
    static func setPolicy(_ policy: ClipboardDevicePolicy, peerID: String, anySessionHasEffectiveInput: Bool,
                          defaults: UserDefaults = .standard) -> Bool {
        guard !policy.widens(self.policy(peerID: peerID, defaults: defaults)) || !anySessionHasEffectiveInput else { return false }
        var all = load(defaults)
        if policy == .default { all.removeValue(forKey: peerID) } else { all[peerID] = try? JSONEncoder().encode(policy) }
        defaults.set(all, forKey: key)
        return true
    }

    static func removePolicy(peerID: String, defaults: UserDefaults = .standard) {
        var all = load(defaults)
        all.removeValue(forKey: peerID)
        defaults.set(all, forKey: key)
    }
}

/// What the owner sees about the last transfer: never the content.
struct ClipTransferRecord: Equatable {
    var at: Date
    var device: String
    var toMac: Bool
    var summary: String
    var failure: String?
}

struct ClipTransferProgress: Identifiable, Equatable {
    let id: Int
    var device: String
    var summary: String
    var bytes: Int
    var done: Int
}

/// Who a message came from: the app's session, as of this message.
struct ClipboardPeerRef {
    let sessionID: String
    let peerID: String?
    let name: String
    let generation: UInt64
    let send: ([String: Any]) -> Void
}

@MainActor
final class ClipboardHub: ObservableObject {
    static let shared = ClipboardHub()

    private enum K {
        static let enabled = "clipboard.enabled", types = "clipboard.types", files = "clipboard.files"
        static let maxBytes = "clipboard.maxBytes", paused = "clipboard.paused"
        static let seq = "clipboard.sync.seq", lamport = "clipboard.sync.lamport"
    }
    /// Pasteboard types that mark content as private or generated (nspasteboard.org): never sent.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]
    /// Written with every copy MeowDisplay puts on the pasteboard.
    static let markerType = NSPasteboard.PasteboardType("app.meowdisplay.clip")

    private let defaults: UserDefaults
    /// The general pasteboard; tests pass a private one (never the owner's clipboard).
    private let pasteboard: NSPasteboard

    // MARK: Settings (Settings ▸ Clipboard)

    @Published var enabled: Bool { didSet { defaults.set(enabled, forKey: K.enabled); settingsChanged(cancel: !enabled) } }
    @Published var types: ClipTypes { didSet { defaults.set(types.rawValue, forKey: K.types); settingsChanged() } }
    @Published var syncFiles: Bool { didSet { defaults.set(syncFiles, forKey: K.files); settingsChanged() } }
    @Published var maxBytes: Int { didSet { defaults.set(maxBytes, forKey: K.maxBytes); settingsChanged() } }
    @Published var paused: Bool { didSet { defaults.set(paused, forKey: K.paused); settingsChanged(cancel: paused) } }

    // MARK: Status

    @Published private(set) var lastTransfer: ClipTransferRecord?
    @Published private(set) var transfers: [ClipTransferProgress] = []
    /// A device copied files larger than the automatic limit: fetched only on Get Files.
    @Published private(set) var waitingFiles: (device: String, summary: String, bytes: Int)?
    /// A copy made at the same moment as the current one, kept to choose.
    @Published private(set) var alternativeFrom: String?
    @Published private(set) var readAccess = "default"
    @Published private(set) var connectedNames: [String: String] = [:]
    @Published private(set) var skippedPrivate = false

    /// Set by the app: a policy is never widened while a device controls this Mac.
    var anySessionHasEffectiveInput: () -> Bool = { false }

    // MARK: State

    private final class Peer {
        let sessionID: String
        var peerID: String?
        var name: String
        var generation: UInt64
        var send: ([String: Any]) -> Void
        var joined = false
        var wants = Wants()
        var grant: Grant = .none
        /// Allowed this session (kept across connection swaps of the same session).
        var sessionAllowed = false
        var seen: [String: UInt64] = [:]
        init(_ r: ClipboardPeerRef) { sessionID = r.sessionID; peerID = r.peerID; name = r.name; generation = r.generation; send = r.send }
    }
    private enum Grant: Equatable { case none, asking, denied, session, always }
    private struct Wants { var on = false; var dir = ClipDirection.both; var types = ClipTypes.all; var files = true; var max = ClipboardWire.defaultMaxBytes }

    /// What the Mac can hand out for one event.
    private enum Source { case data(Data), file(URL, size: Int, modified: Date?) }
    private struct Served { var event: ClipEvent; var sources: [Int: Source]; var originSession: String? }

    private final class Job {
        let id: Int
        let event: ClipEvent
        let sessionID: String
        let staging: URL
        var queue: [(blob: Int, size: Int, hash: String?, target: Target)]
        var fetch: ClipBlobFetch?
        var handle: FileHandle?
        var reps: [Int: Data] = [:]      // blob → bytes
        var total: Int
        var done = 0
        var lastActivity = Date()
        let makeCurrentCopy: Bool
        enum Target { case rep, file(Int) }
        init(id: Int, event: ClipEvent, sessionID: String, staging: URL, queue: [(Int, Int, String?, Target)], makeCurrentCopy: Bool) {
            self.id = id; self.event = event; self.sessionID = sessionID; self.staging = staging
            self.queue = queue.map { (blob: $0.0, size: $0.1, hash: $0.2, target: $0.3) }
            self.total = queue.reduce(0) { $0 + $1.1 }
            self.makeCurrentCopy = makeCurrentCopy
        }
    }

    private var peers: [String: Peer] = [:]
    private var sync: ClipboardSync
    private var served: [ClipEventID: Served] = [:]
    private var servedOrder: [ClipEventID] = []
    private var jobs: [Int: Job] = [:]
    private var nextReq = 1
    private var alternative: (event: ClipEvent, sessionID: String)?
    private var waitingFilesEvent: (event: ClipEvent, sessionID: String)?
    private var timer: Timer?
    private var lastChange: Int
    private var ownChange: Int?
    private let io = DispatchQueue(label: "meow.clipboard.io", qos: .utility)
    private let stagingRoot: URL

    init(defaults: UserDefaults = .standard, pasteboard: NSPasteboard = .general, origin: String? = nil, staging: URL? = nil) {
        self.defaults = defaults
        self.pasteboard = pasteboard
        stagingRoot = staging ?? FileManager.default.temporaryDirectory.appendingPathComponent("MeowDisplay-Clipboard", isDirectory: true)
        enabled = defaults.bool(forKey: K.enabled)
        types = ClipTypes(rawValue: defaults.string(forKey: K.types) ?? "") ?? .all
        syncFiles = defaults.object(forKey: K.files) as? Bool ?? true
        let stored = defaults.integer(forKey: K.maxBytes)
        maxBytes = ClipboardWire.sizeChoices.contains(stored) ? stored : ClipboardWire.defaultMaxBytes
        paused = defaults.bool(forKey: K.paused)
        sync = ClipboardSync(origin: origin ?? TrustStore.shared.installID() ?? "mac",
                             seq: UInt64(max(0, defaults.integer(forKey: K.seq))), lamport: UInt64(max(0, defaults.integer(forKey: K.lamport))))
        lastChange = pasteboard.changeCount
        // Nothing transferred survives a relaunch.
        try? FileManager.default.removeItem(at: stagingRoot)
        refreshReadAccess()
    }

    // MARK: Sessions

    /// The app's live sessions: anything else is gone (its prompt and transfers too).
    func retain(sessionIDs: Set<String>) {
        for id in peers.keys where !sessionIDs.contains(id) { detach(id) }
    }

    /// The session's connection changed: it joins again on the new one.
    func connectionReset(sessionID: String) {
        guard let p = peers[sessionID] else { return }
        p.joined = false
        cancelJobs { $0.sessionID == sessionID }
        ClipboardConsentPresenter.dismiss(sessionID: sessionID)
        if p.grant == .asking { p.grant = .none }
        updateWatcher()
    }

    private func detach(_ sessionID: String) {
        peers.removeValue(forKey: sessionID)
        connectedNames.removeValue(forKey: sessionID)
        cancelJobs { $0.sessionID == sessionID }
        ClipboardConsentPresenter.dismiss(sessionID: sessionID)
        if alternative?.sessionID == sessionID { alternative = nil; alternativeFrom = nil }
        if waitingFilesEvent?.sessionID == sessionID { waitingFilesEvent = nil; waitingFiles = nil }
        updateWatcher()
    }

    private func peer(_ r: ClipboardPeerRef) -> Peer {
        if let p = peers[r.sessionID] {
            if p.generation != r.generation || p.peerID != r.peerID {
                // A new connection of the same session: same grant, new channel.
                if p.peerID != r.peerID { p.grant = .none; p.sessionAllowed = false }
                p.generation = r.generation; p.peerID = r.peerID; p.send = r.send
            }
            p.name = r.name
            return p
        }
        let p = Peer(r)
        peers[r.sessionID] = p
        return p
    }

    private func policy(_ p: Peer) -> ClipboardDevicePolicy {
        p.peerID.map { ClipboardDevicePolicyStore.policy(peerID: $0, defaults: defaults) } ?? .default
    }

    private func ready(_ p: Peer) -> Bool {
        enabled && !paused && p.joined && p.wants.on && (p.grant == .session || p.grant == .always) && policy(p).access != .block
    }
    private func toDevice(_ p: Peer) -> Bool { ready(p) && policy(p).direction.toDeviceAllowed && p.wants.dir.toDeviceAllowed }
    private func toMac(_ p: Peer) -> Bool { ready(p) && policy(p).direction.toMacAllowed && p.wants.dir.toMacAllowed }
    private func typesFor(_ p: Peer) -> ClipTypes { types == .text || p.wants.types == .text ? .text : .all }
    private func filesFor(_ p: Peer) -> Bool { syncFiles && p.wants.files && typesFor(p) == .all }

    // MARK: Messages from a device

    func handle(_ r: ClipboardPeerRef, _ m: [String: Any]) {
        let p = peer(r)
        switch m["op"] as? String {
        case "join":
            p.joined = true
            p.wants = Wants(on: m["on"] as? Bool ?? false,
                            dir: (m["dir"] as? String).flatMap(ClipDirection.init(rawValue:)) ?? .both,
                            types: (m["types"] as? String).flatMap(ClipTypes.init(rawValue:)) ?? .all,
                            files: m["files"] as? Bool ?? true,
                            max: min(max(m["max"] as? Int ?? ClipboardWire.defaultMaxBytes, 0), ClipboardWire.sizeChoices.last!))
            var seen: [String: UInt64] = [:]
            for (k, v) in (m["seen"] as? [String: Any] ?? [:]).prefix(64) where k.count <= ClipboardWire.maxOriginLength {
                if let n = v as? Int, n >= 0 { seen[k] = UInt64(n) }
            }
            p.seen = seen
            sync.merge(seen: seen)   // a reconnect is never a new copy
            persistCounters()
            connectedNames[p.sessionID] = p.name
            evaluateGrant(p)
        case "leave":
            p.wants.on = false
            sendState(p)
            cancelJobs { $0.sessionID == p.sessionID }
            updateWatcher()
        case "event":
            guard let e = ClipEvent.parse(m) else { return }
            receive(e, from: p)
        case "read":
            serveRead(m, to: p)
        case "data", "readEnd":
            jobMessage(m, from: p)
        default:
            break
        }
    }

    private func evaluateGrant(_ p: Peer) {
        guard enabled, p.wants.on else { sendState(p); updateWatcher(); return }
        let pol = policy(p)
        switch pol.access {
        case .block: p.grant = .denied
        case .always: p.grant = .always
        case .ask:
            if p.sessionAllowed { p.grant = .session } else if p.grant != .asking {
                p.grant = .asking
                let sessionID = p.sessionID
                ClipboardConsentPresenter.present(name: p.name, sessionID: sessionID,
                                                  alwaysAllowed: p.peerID != nil && !anySessionHasEffectiveInput()) { [weak self] decision in
                    self?.consentDecided(sessionID: sessionID, decision)
                }
            }
        }
        sendState(p)
        if ready(p) { catchUp(p) }
        updateWatcher()
    }

    private func consentDecided(sessionID: String, _ decision: ClipboardConsentDecision) {
        guard let p = peers[sessionID] else { return }
        switch decision {
        case .deny: p.grant = .denied
        case .session: p.grant = .session; p.sessionAllowed = true
        case .always:
            p.sessionAllowed = true
            p.grant = .session
            if let id = p.peerID {
                var pol = ClipboardDevicePolicyStore.policy(peerID: id, defaults: defaults)
                pol.access = .always
                if ClipboardDevicePolicyStore.setPolicy(pol, peerID: id, anySessionHasEffectiveInput: anySessionHasEffectiveInput(), defaults: defaults) {
                    p.grant = .always
                } else {
                    Log.info("clipboard: Always Allow not stored (a device controls this Mac); allowed for this session")
                }
            }
        }
        sendState(p)
        if ready(p) { catchUp(p) }
        updateWatcher()
        objectWillChange.send()
    }

    /// The device hasn't seen the current shared copy (it was made while it was away).
    private func catchUp(_ p: Peer) {
        guard toDevice(p), let cur = sync.current, (p.seen[cur.id.origin] ?? 0) < cur.id.seq,
              let s = served[cur.id], s.originSession != p.sessionID else { return }
        send(s, to: p)
    }

    // MARK: Settings and policy changes

    private func settingsChanged(cancel: Bool = false) {
        if cancel { cancelJobs { _ in true }; clearStaging(keep: nil) }
        for p in peers.values {
            if enabled, p.joined, p.wants.on, p.grant == .none || p.grant == .denied { evaluateGrant(p) } else { sendState(p) }
        }
        updateWatcher()
    }

    /// The owner changed a device's policy (Settings ▸ Clipboard / Devices): applies at once.
    func setPolicy(_ policy: ClipboardDevicePolicy, peerID: String) {
        guard ClipboardDevicePolicyStore.setPolicy(policy, peerID: peerID, anySessionHasEffectiveInput: anySessionHasEffectiveInput(),
                                                   defaults: defaults) else { return }
        for p in peers.values where p.peerID == peerID {
            switch policy.access {
            case .block: p.grant = .denied; cancelJobs { $0.sessionID == p.sessionID }
            case .always: p.grant = .always
            case .ask: if p.grant == .always { p.grant = p.sessionAllowed ? .session : .none }
            }
            if p.grant == .none { evaluateGrant(p) } else { sendState(p) }
        }
        updateWatcher()
        objectWillChange.send()
    }

    func policy(peerID: String) -> ClipboardDevicePolicy { ClipboardDevicePolicyStore.policy(peerID: peerID, defaults: defaults) }

    /// Revoke now: this session's Allow ends, transfers stop, the device must ask again.
    func revoke(peerID: String) {
        for p in peers.values where p.peerID == peerID {
            p.sessionAllowed = false
            p.grant = .denied
            cancelJobs { $0.sessionID == p.sessionID }
            sendState(p, revoked: true)
        }
        var pol = ClipboardDevicePolicyStore.policy(peerID: peerID, defaults: defaults)
        if pol.access == .always { pol.access = .ask; ClipboardDevicePolicyStore.setPolicy(pol, peerID: peerID, anySessionHasEffectiveInput: false, defaults: defaults) }
        updateWatcher()
    }

    func forget(peerID: String) {
        ClipboardDevicePolicyStore.removePolicy(peerID: peerID, defaults: defaults)
    }

    /// Settings ▸ Clipboard ▸ Clear: transfers in progress and waiting files are dropped.
    func clearPending() {
        cancelJobs { _ in true }
        waitingFilesEvent = nil; waitingFiles = nil
        alternative = nil; alternativeFrom = nil
        clearStaging(keep: nil)
    }

    private func sendState(_ p: Peer, revoked: Bool = false) {
        var m: [String: Any] = ["type": ClipboardWire.type, "op": "state"]
        let state: String
        if !enabled { state = "off" } else if revoked { state = "revoked" } else if !p.wants.on { state = "idle" } else if paused { state = "paused" } else {
            switch p.grant {
            case .none, .asking: state = "asking"
            case .denied: state = "denied"
            case .session, .always: state = policy(p).access == .block ? "denied" : "ready"
            }
        }
        m["state"] = state
        if state == "ready" {
            m["toDevice"] = toDevice(p); m["toMac"] = toMac(p)
            m["types"] = typesFor(p).rawValue; m["files"] = filesFor(p); m["max"] = maxBytes
            m["duration"] = p.grant == .always ? "always" : "session"
            m["macRead"] = readAccess
            m["seen"] = sync.seen.mapValues { Int($0) }
        }
        p.send(m)
    }

    // MARK: The Mac's own copies

    private func updateWatcher() {
        let need = enabled && !paused && peers.values.contains { ready($0) }
        if need, timer == nil {
            lastChange = pasteboard.changeCount   // what was there before is not a new copy
            let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
            RunLoop.main.add(t, forMode: .common)
            timer = t
        } else if !need, let t = timer {
            t.invalidate()
            timer = nil
        }
    }

    private func refreshReadAccess() {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow: readAccess = "allowed"
            case .alwaysDeny: readAccess = "denied"
            case .ask: readAccess = "ask"
            default: readAccess = "default"
            }
        } else {
            readAccess = "allowed"
        }
    }

    /// Tests: one watcher tick now.
    func pollNow() { poll() }

    private func poll() {
        let pb = pasteboard
        let cc = pb.changeCount
        guard cc != lastChange else { return }
        lastChange = cc
        if cc == ownChange { return }
        let targets = peers.values.filter { toDevice($0) }
        guard !targets.isEmpty else { return }
        let available = Set((pb.types ?? []).map(\.rawValue))
        if !available.isDisjoint(with: Self.privateTypes) || available.contains(Self.markerType.rawValue) {
            skippedPrivate = !available.contains(Self.markerType.rawValue)
            return
        }
        skippedPrivate = false
        refreshReadAccess()
        if readAccess == "denied" { return }
        guard let (items, files, sources) = readPasteboard(pb) else { return }
        guard let header = sync.localCopy(contentHash: ClipEvent.contentHash(items: items, files: files)) else { return }
        persistCounters()
        let event = ClipEvent(header: header, at: Int64(Date().timeIntervalSince1970 * 1000), items: items, files: files)
        let s = Served(event: event, sources: sources, originSession: nil)
        remember(s)
        alternative = nil; alternativeFrom = nil
        Log.info("clipboard: local copy \(header.id.seq): \(items.count) item(s), \(files.count) file entries, \(event.totalBytes) bytes")
        for p in targets { send(s, to: p) }
        lastTransfer = ClipTransferRecord(at: Date(), device: targets.map(\.name).joined(separator: ", "), toMac: false, summary: event.summary)
    }

    /// Reads what is copied, within the size limit; nil when there is nothing to send.
    private func readPasteboard(_ pb: NSPasteboard) -> ([ClipItem], [ClipFile], [Int: Source])? {
        var items: [ClipItem] = []
        var files: [ClipFile] = []
        var sources: [Int: Source] = [:]
        var blob = 0
        var inlineLeft = ClipboardWire.inlineBytes
        func rep(_ kind: ClipKind, _ data: Data) -> ClipRep? {
            guard data.count <= maxBytes else { return nil }
            var r = ClipRep(kind: kind, size: data.count, hash: ClipHash.of(data))
            if data.count <= inlineLeft { r.inline = data; inlineLeft -= data.count } else { r.blob = blob; sources[blob] = .data(data); blob += 1 }
            return r
        }
        let all = types == .all
        var fileURLs: [URL] = []
        for item in (pb.pasteboardItems ?? []).prefix(ClipboardWire.maxItems) {
            if let s = item.string(forType: .fileURL), let u = URL(string: s), u.isFileURL { fileURLs.append(u); continue }
            var reps: [ClipRep] = []
            if let s = item.string(forType: .string), let r = rep(.text, Data(s.utf8)) { reps.append(r) }
            if let s = item.string(forType: .URL), let r = rep(.url, Data(s.utf8)) { reps.append(r) }
            if all {
                if let d = item.data(forType: .html), let r = rep(.html, d) { reps.append(r) }
                if let d = item.data(forType: .rtf), let r = rep(.rtf, d) { reps.append(r) }
                if let d = item.data(forType: .png), let r = rep(.png, d) { reps.append(r) }
                else if let d = item.data(forType: NSPasteboard.PasteboardType(UTType.jpeg.identifier)), let r = rep(.jpeg, d) { reps.append(r) }
                else if let t = item.data(forType: .tiff), let png = NSBitmapImageRep(data: t)?.representation(using: .png, properties: [:]),
                        let r = rep(.png, png) { reps.append(r) }
            }
            if !reps.isEmpty { items.append(ClipItem(reps: Array(reps.prefix(ClipboardWire.maxReps)))) }
        }
        if all, syncFiles, !fileURLs.isEmpty {
            for top in fileURLs {
                guard files.count < ClipboardWire.maxFiles else { break }
                let base = top.deletingLastPathComponent()
                let values = try? top.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey, .fileSizeKey, .contentModificationDateKey])
                if values?.isSymbolicLink == true { continue }
                func add(_ url: URL, _ v: URLResourceValues?) {
                    let path = Array(url.standardizedFileURL.pathComponents.dropFirst(base.standardizedFileURL.pathComponents.count))
                    guard !path.isEmpty, path.count <= ClipboardWire.maxDepth, path.allSatisfy(ClipFiles.isSafeName) else { return }
                    if v?.isDirectory == true {
                        files.append(ClipFile(path: path, size: 0, dir: true))
                    } else {
                        let size = v?.fileSize ?? 0
                        files.append(ClipFile(path: path, size: size, dir: false, blob: blob))
                        sources[blob] = .file(url, size: size, modified: v?.contentModificationDate)
                        blob += 1
                    }
                }
                add(top, values)
                if values?.isDirectory == true, let e = FileManager.default.enumerator(
                    at: top, includingPropertiesForKeys: [.isDirectoryKey, .isSymbolicLinkKey, .fileSizeKey, .contentModificationDateKey], options: [.skipsPackageDescendants]) {
                    for case let u as URL in e {
                        if files.count >= ClipboardWire.maxFiles { break }
                        let v = try? u.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey, .fileSizeKey, .contentModificationDateKey])
                        if v?.isSymbolicLink == true { continue }   // links are never followed
                        add(u, v)
                    }
                }
            }
        }
        if items.isEmpty && files.isEmpty { return nil }
        return (items, files, sources)
    }

    private func persistCounters() {
        defaults.set(Int(sync.seq), forKey: K.seq)
        defaults.set(Int(sync.lamport), forKey: K.lamport)
    }

    private func remember(_ s: Served) {
        served[s.event.id] = s
        servedOrder.removeAll { $0 == s.event.id }
        servedOrder.append(s.event.id)
        while servedOrder.count > 3 { served.removeValue(forKey: servedOrder.removeFirst()) }
    }

    /// The event as this device gets it: what fits inside, the rest by `read`.
    private func send(_ s: Served, to p: Peer) {
        var e = s.event
        let textOnly = typesFor(p) == .text
        e.items = e.items.compactMap { item in
            let reps = item.reps.filter { (!textOnly || $0.kind.isText) && $0.size <= p.wants.max }
            return reps.isEmpty ? nil : ClipItem(reps: reps)
        }
        if !filesFor(p) { e.files = [] }
        guard !e.items.isEmpty || !e.files.isEmpty else { return }
        p.send(e.wire)
    }

    // MARK: Serving reads

    private func serveRead(_ m: [String: Any], to p: Peer) {
        guard let req = m["req"] as? Int, let origin = m["o"] as? String, let seqInt = m["s"] as? Int, seqInt > 0,
              let b = m["b"] as? Int, let off = m["off"] as? Int, off >= 0, let n = m["n"] as? Int, n > 0, n <= ClipboardWire.readMax else { return }
        let send = p.send
        guard toDevice(p), let s = served[ClipEventID(origin: origin, seq: UInt64(seqInt))], let source = s.sources[b] else {
            ClipBlobWire.answer(req: req, offset: off, bytes: nil, error: toDevice(p) ? "gone" : "denied").forEach(send)
            return
        }
        if case .file = source, !filesFor(p) {
            ClipBlobWire.answer(req: req, offset: off, bytes: nil, error: "denied").forEach(send)
            return
        }
        let box = ClipboardSendBox(send)
        io.async {
            let frames: [[String: Any]]
            switch source {
            case .data(let d):
                frames = off <= d.count ? ClipBlobWire.answer(req: req, offset: off, bytes: d.subdata(in: off..<min(d.count, off + n)))
                                        : ClipBlobWire.answer(req: req, offset: off, bytes: nil, error: "badRange")
            case .file(let url, let size, let modified):
                let v = try? url.resourceValues(forKeys: [.fileSizeKey, .contentModificationDateKey, .isSymbolicLinkKey])
                if v == nil { frames = ClipBlobWire.answer(req: req, offset: off, bytes: nil, error: "gone") }
                else if v?.fileSize != size || v?.contentModificationDate != modified || v?.isSymbolicLink == true {
                    frames = ClipBlobWire.answer(req: req, offset: off, bytes: nil, error: "changed")
                } else if let h = try? FileHandle(forReadingFrom: url) {
                    defer { try? h.close() }
                    try? h.seek(toOffset: UInt64(off))
                    let d = (try? h.read(upToCount: n)) ?? Data()
                    frames = ClipBlobWire.answer(req: req, offset: off, bytes: d)
                } else {
                    frames = ClipBlobWire.answer(req: req, offset: off, bytes: nil, error: "permission")
                }
            }
            let out = ClipboardFrames(frames)
            DispatchQueue.main.async { out.frames.forEach(box.send) }
        }
    }

    // MARK: A device's copies

    private func receive(_ e: ClipEvent, from p: Peer) {
        guard toMac(p) else { return }
        let decision = sync.receive(e.header)
        persistCounters()
        switch decision {
        case .apply:
            alternative = nil; alternativeFrom = nil
            startApply(e, from: p, makeCurrentCopy: false)
        case .alternative:
            alternative = (e, p.sessionID)
            alternativeFrom = p.name
        case .duplicate, .echo, .older:
            break
        }
    }

    /// Fetches what is needed (within the limit), then puts it on the pasteboard.
    private func startApply(_ e: ClipEvent, from p: Peer, makeCurrentCopy: Bool, filesNow: Bool = false) {
        cancelJobs { !$0.makeCurrentCopy || makeCurrentCopy }
        let textOnly = typesFor(p) == .text
        var event = e
        event.items = e.items.compactMap { item in
            let reps = item.reps.filter { (!textOnly || $0.kind.isText) && ($0.inline != nil || $0.size <= maxBytes) }
            return reps.isEmpty ? nil : ClipItem(reps: reps)
        }
        let fileBytes = e.files.reduce(0) { $0 + $1.size }
        var takeFiles = filesFor(p) && !e.files.isEmpty
        if takeFiles, fileBytes > maxBytes, !filesNow {
            waitingFilesEvent = (e, p.sessionID)
            waitingFiles = (p.name, e.summary, fileBytes)
            takeFiles = false
        }
        if !takeFiles { event.files = [] }
        guard !event.items.isEmpty || !event.files.isEmpty else {
            lastTransfer = ClipTransferRecord(at: Date(), device: p.name, toMac: true, summary: e.summary,
                                              failure: waitingFiles == nil ? String(localized: "Too large or not a type this Mac syncs") : nil)
            return
        }
        var queue: [(Int, Int, String?, Job.Target)] = []
        for item in event.items { for r in item.reps where r.inline == nil { if let b = r.blob { queue.append((b, r.size, r.hash, .rep)) } } }
        for (i, f) in event.files.enumerated() where !f.dir { if let b = f.blob { queue.append((b, f.size, nil, .file(i))) } }
        let staging = stagingRoot.appendingPathComponent("\(abs(e.id.origin.hashValue))-\(e.id.seq)", isDirectory: true)
        let job = Job(id: nextReq, event: event, sessionID: p.sessionID, staging: staging, queue: queue, makeCurrentCopy: makeCurrentCopy)
        nextReq += 1
        if !event.files.isEmpty {
            try? FileManager.default.createDirectory(at: staging, withIntermediateDirectories: true)
            for f in event.files where f.dir {
                try? FileManager.default.createDirectory(at: fileURL(staging, f.path), withIntermediateDirectories: true)
            }
        }
        jobs[job.id] = job
        transfers.append(ClipTransferProgress(id: job.id, device: p.name, summary: e.summary, bytes: job.total, done: 0))
        advance(job)
    }

    private func fileURL(_ staging: URL, _ path: [String]) -> URL {
        path.reduce(staging) { $0.appendingPathComponent($1) }
    }

    private func advance(_ job: Job) {
        guard jobs[job.id] != nil, let p = peers[job.sessionID] else { return finish(job, failure: "gone") }
        if var fetch = job.fetch, let read = fetch.nextRead() {
            job.fetch = fetch
            p.send(read)
            scheduleTimeout(job)
            return
        }
        try? job.handle?.close(); job.handle = nil
        guard !job.queue.isEmpty else { return finish(job, failure: nil) }
        let next = job.queue.removeFirst()
        var fetch = ClipBlobFetch(req: nextReq, id: job.event.id, blob: next.blob, size: next.size, expectedHash: next.hash)
        nextReq += 1
        if case .file(let i) = next.target {
            let url = fileURL(job.staging, job.event.files[i].path)
            FileManager.default.createFile(atPath: url.path, contents: nil)
            job.handle = try? FileHandle(forWritingTo: url)
            if job.handle == nil { return finish(job, failure: "noSpace") }
        }
        if next.size == 0 { job.fetch = nil; return advance(job) }
        let read = fetch.nextRead()!
        job.fetch = fetch
        p.send(read)
        scheduleTimeout(job)
    }

    private func jobMessage(_ m: [String: Any], from p: Peer) {
        guard let req = m["req"] as? Int,
              let job = jobs.values.first(where: { $0.sessionID == p.sessionID && $0.fetch?.req == req }), var fetch = job.fetch else { return }
        job.lastActivity = Date()
        switch fetch.handle(m) {
        case .more:
            job.fetch = fetch
        case .rangeDone(let bytes):
            job.fetch = fetch
            job.done += bytes.count
            if let h = job.handle { h.write(bytes) } else { job.reps[fetch.blob, default: Data()].append(bytes) }
            if let i = transfers.firstIndex(where: { $0.id == job.id }) { transfers[i].done = job.done }
            if fetch.done { job.fetch = nil }
            advance(job)
        case .failed(let code):
            finish(job, failure: code)
        }
    }

    private func scheduleTimeout(_ job: Job) {
        job.lastActivity = Date()
        let id = job.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 16) { [weak self] in
            MainActor.assumeIsolated {
                guard let self, let j = self.jobs[id], Date().timeIntervalSince(j.lastActivity) >= 15 else { return }
                self.finish(j, failure: "timeout")
            }
        }
    }

    private func cancelJobs(_ which: (Job) -> Bool) {
        for j in jobs.values where which(j) {
            try? j.handle?.close()
            jobs.removeValue(forKey: j.id)
            transfers.removeAll { $0.id == j.id }
            try? FileManager.default.removeItem(at: j.staging)
        }
    }

    private func finish(_ job: Job, failure: String?) {
        try? job.handle?.close(); job.handle = nil
        jobs.removeValue(forKey: job.id)
        transfers.removeAll { $0.id == job.id }
        let device = peers[job.sessionID]?.name ?? String(localized: "A device")
        if let failure {
            try? FileManager.default.removeItem(at: job.staging)
            Log.info("clipboard: transfer \(job.id) failed: \(failure)")
            lastTransfer = ClipTransferRecord(at: Date(), device: device, toMac: true, summary: job.event.summary, failure: Self.failureText(failure))
            return
        }
        // A newer copy happened meanwhile: this one never overwrites it.
        guard job.makeCurrentCopy || sync.isCurrent(job.event.id) else {
            try? FileManager.default.removeItem(at: job.staging)
            return
        }
        write(job)
        lastTransfer = ClipTransferRecord(at: Date(), device: device, toMac: true, summary: job.event.summary)
        if job.makeCurrentCopy { return }   // the watcher sends it on as a new copy
        // Relay to the other devices: the Mac now serves what it fetched.
        var sources: [Int: Source] = [:]
        var e = job.event
        var blob = 0
        var inlineLeft = ClipboardWire.inlineBytes
        e.items = e.items.map { item in
            ClipItem(reps: item.reps.compactMap { r in
                guard let data = r.inline ?? r.blob.flatMap({ job.reps[$0] }) else { return nil }
                var out = ClipRep(kind: r.kind, size: data.count, hash: r.hash)
                if data.count <= inlineLeft { out.inline = data; inlineLeft -= data.count } else { out.blob = blob; sources[blob] = .data(data); blob += 1 }
                return out
            })
        }.filter { !$0.reps.isEmpty }
        e.files = e.files.map { f in
            guard !f.dir else { return f }
            let url = fileURL(job.staging, f.path)
            let v = try? url.resourceValues(forKeys: [.fileSizeKey, .contentModificationDateKey])
            sources[blob] = .file(url, size: v?.fileSize ?? f.size, modified: v?.contentModificationDate)
            defer { blob += 1 }
            return ClipFile(path: f.path, size: f.size, dir: false, blob: blob)
        }
        let s = Served(event: e, sources: sources, originSession: job.sessionID)
        remember(s)
        clearStaging(keep: job.staging)
        for p in peers.values where p.sessionID != job.sessionID && p.peerID != e.id.origin && toDevice(p) { send(s, to: p) }
    }

    /// Puts a device's copy on this Mac's pasteboard, for this Mac only.
    private func write(_ job: Job) {
        let pb = pasteboard
        pb.prepareForNewContents(with: .currentHostOnly)
        var objects: [NSPasteboardWriting] = []
        for (i, item) in job.event.items.enumerated() {
            let out = NSPasteboardItem()
            for r in item.reps {
                guard let data = r.inline ?? r.blob.flatMap({ job.reps[$0] }) else { continue }
                switch r.kind {
                case .text: out.setString(String(decoding: data, as: UTF8.self), forType: .string)
                case .url: out.setString(String(decoding: data, as: UTF8.self), forType: .URL)
                case .html: out.setData(data, forType: .html)
                case .rtf: out.setData(data, forType: .rtf)
                case .png: out.setData(data, forType: .png)
                case .jpeg: out.setData(data, forType: NSPasteboard.PasteboardType(UTType.jpeg.identifier))
                }
            }
            // Marked as MeowDisplay's, so the watcher doesn't send it on — unless the owner chose
            // it (an alternative or waiting files): then it is a new copy from this Mac.
            if i == 0, !job.makeCurrentCopy { out.setString("\(job.event.id.origin):\(job.event.id.seq)", forType: Self.markerType) }
            objects.append(out)
        }
        // Files: the copied items themselves (not their contents), from the private staging folder.
        let tops = job.event.files.filter { $0.path.count == 1 }.map { fileURL(job.staging, $0.path) as NSURL }
        objects.append(contentsOf: tops)
        if !tops.isEmpty, job.event.items.isEmpty, !job.makeCurrentCopy {
            let marker = NSPasteboardItem()
            marker.setString("\(job.event.id.origin):\(job.event.id.seq)", forType: Self.markerType)
            objects.append(marker)
        }
        pb.writeObjects(objects)
        if !job.makeCurrentCopy { ownChange = pb.changeCount }
        lastChange = job.makeCurrentCopy ? lastChange : pb.changeCount
    }

    private func clearStaging(keep: URL?) {
        guard let entries = try? FileManager.default.contentsOfDirectory(at: stagingRoot, includingPropertiesForKeys: nil) else { return }
        let busy = Set(jobs.values.map(\.staging.standardizedFileURL))
        for u in entries where u.standardizedFileURL != keep?.standardizedFileURL && !busy.contains(u.standardizedFileURL) {
            try? FileManager.default.removeItem(at: u)
        }
    }

    // MARK: Owner actions

    /// Waiting files (over the automatic limit): fetch them now.
    func getWaitingFiles() {
        guard let w = waitingFilesEvent, let p = peers[w.sessionID], toMac(p) else { return }
        waitingFilesEvent = nil; waitingFiles = nil
        startApply(w.event, from: p, makeCurrentCopy: !sync.isCurrent(w.event.id), filesNow: true)
    }

    /// Use the other device's copy made at the same moment: it becomes a new copy here.
    func useAlternative() {
        guard let a = alternative, let p = peers[a.sessionID], toMac(p) else { return }
        alternative = nil; alternativeFrom = nil
        sync.dropAlternative()
        startApply(a.event, from: p, makeCurrentCopy: true)
    }

    static func failureText(_ code: String) -> String {
        switch code {
        case "timeout": return String(localized: "The device stopped answering")
        case "changed": return String(localized: "The file changed while it was copied")
        case "gone": return String(localized: "No longer available on the device")
        case "denied": return String(localized: "Not allowed")
        case "digest": return String(localized: "The data arrived damaged")
        case "noSpace": return String(localized: "Not enough space on this Mac")
        default: return String(localized: "Transfer failed")
        }
    }
}

/// Reply frames crossing to the main queue (dictionaries aren't Sendable).
private final class ClipboardFrames: @unchecked Sendable {
    let frames: [[String: Any]]
    init(_ frames: [[String: Any]]) { self.frames = frames }
}

/// Lets a send closure cross to the main queue (dictionaries aren't Sendable).
private final class ClipboardSendBox: @unchecked Sendable {
    let send: ([String: Any]) -> Void
    init(_ send: @escaping ([String: Any]) -> Void) { self.send = send }
}

// MARK: - Owner prompt

enum ClipboardConsentDecision { case deny, session, always }

/// "<Device> wants to share the clipboard with this Mac": Not Now / Allow This Session / Always
/// Allow. One question at a time; doesn't activate the app; buttons arm after a moment.
@MainActor
enum ClipboardConsentPresenter {
    private struct Request { let sessionID: String; let name: String; let alwaysAllowed: Bool; var decide: (ClipboardConsentDecision) -> Void }
    private static var shown: Request?
    private static var queue: [Request] = []
    private static var panel: NSPanel?
    private static var delegate: PanelDelegate?

    static func present(name: String, sessionID: String, alwaysAllowed: Bool, decide: @escaping (ClipboardConsentDecision) -> Void) {
        if shown?.sessionID == sessionID { shown?.decide = decide; return }
        if let i = queue.firstIndex(where: { $0.sessionID == sessionID }) { queue[i].decide = decide; return }
        queue.append(Request(sessionID: sessionID, name: name, alwaysAllowed: alwaysAllowed, decide: decide))
        showNext()
    }

    static func dismiss(sessionID: String) {
        queue.removeAll { $0.sessionID == sessionID }
        guard shown?.sessionID == sessionID else { return }
        shown = nil
        close()
        showNext()
    }

    fileprivate static func answer(_ d: ClipboardConsentDecision) {
        guard let s = shown else { return }
        shown = nil
        close()
        s.decide(d)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) { MainActor.assumeIsolated { showNext() } }
    }

    private static func close() {
        guard let p = panel else { return }
        panel = nil
        p.delegate = nil
        delegate = nil
        p.orderOut(nil)
        p.close()
    }

    private static func showNext() {
        guard shown == nil, !queue.isEmpty else { return }
        let r = queue.removeFirst()
        shown = r
        let p = NSPanel(contentRect: NSRect(x: 0, y: 0, width: 380, height: 1), styleMask: [.titled, .closable, .nonactivatingPanel],
                        backing: .buffered, defer: false)
        p.title = String(localized: "Clipboard Request")
        p.isFloatingPanel = true
        p.level = .modalPanel
        p.hidesOnDeactivate = false
        p.isReleasedWhenClosed = false
        let d = PanelDelegate()
        delegate = d
        p.delegate = d
        let host = NSHostingController(rootView: ClipboardConsentView(name: r.name, alwaysAllowed: r.alwaysAllowed) { answer($0) })
        host.sizingOptions = [.preferredContentSize]
        p.contentViewController = host
        p.center()
        p.orderFrontRegardless()
        p.makeKey()
        panel = p
    }

    private final class PanelDelegate: NSObject, NSWindowDelegate {
        func windowWillClose(_ notification: Notification) { MainActor.assumeIsolated { ClipboardConsentPresenter.answer(.deny) } }
    }
}

private struct ClipboardConsentView: View {
    let name: String
    let alwaysAllowed: Bool
    let decide: (ClipboardConsentDecision) -> Void
    @State private var armed = false

    var body: some View {
        VStack(spacing: 18) {
            VStack(spacing: 6) {
                Text("\(name) wants to share the clipboard with this Mac")
                    .font(.headline).multilineTextAlignment(.center).fixedSize(horizontal: false, vertical: true)
                Text("What you copy here can be pasted there, and the other way round, as set in Settings ▸ Clipboard. Copies can contain passwords or private messages; MeowDisplay skips items that apps mark as private, but can't recognize every one. Clipboard sharing never gives control of this Mac or access to its files.")
                    .font(.subheadline).foregroundStyle(.secondary).multilineTextAlignment(.center).fixedSize(horizontal: false, vertical: true)
                if !alwaysAllowed {
                    Text("Always Allow isn't available while a device controls this Mac.")
                        .font(.caption).foregroundStyle(.secondary).multilineTextAlignment(.center)
                }
            }
            HStack(spacing: 8) {
                Button("Not Now") { decide(.deny) }.keyboardShortcut(.cancelAction)
                Button("Allow This Session") { decide(.session) }.disabled(!armed)
                if alwaysAllowed { Button("Always Allow") { decide(.always) }.disabled(!armed) }
            }
        }
        .padding(20)
        .frame(width: 380)
        .task {
            try? await Task.sleep(nanoseconds: 600_000_000)
            armed = true
        }
    }
}
